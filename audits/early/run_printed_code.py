#!/usr/bin/env python3
"""Run the code the Hub papers print, as printed (step S30, item 2).

Usage: python3 audits/early/run_printed_code.py <research-hub checkout> [--out audits/early/printed-code.md]

Takes every code block printed in the modelling paper (economic-modeling-simulation: the HTML page's
<pre> blocks and the PDF's "python" blocks) and runs each one twice:
  1. as printed, in an empty namespace (no imports added);
  2. with the two imports the code plainly assumes (`import random`, `import numpy as np`), and with
     `random` bound to numpy.random where the block calls `random.normal` (a numpy-only function).
After defining a block, it calls the block's entry point with the arguments the paper states, if any.
Nothing in the printed code is changed. The transfer-design paper (optimal-transfer-design) prints
no code, only parameter distributions (its Appendix A), so there is nothing to run for it.
"""
import html, io, pathlib, re, subprocess, sys, textwrap, traceback, contextlib

def html_blocks(root):
    t = (root / "economic-modeling-simulation.html").read_text()
    for i, b in enumerate(re.findall(r"<pre[^>]*>(.*?)</pre>", t, re.S)):
        c = html.unescape(re.sub(r"<[^>]+>", "", b))
        if re.search(r"\b(def|class) ", c):
            yield f"HTML block {i + 1}", textwrap.dedent(c).strip("\n")

def pdf_blocks(root):
    txt = subprocess.run(["pdftotext", "-layout", str(root / "papers/pdfs/economic-modeling-simulation.pdf"), "-"],
                         capture_output=True, text=True).stdout.splitlines()
    i = 0
    while i < len(txt):
        if txt[i].strip() == "python":
            j, code = i + 1, []
            while j < len(txt):
                line = txt[j]
                if line.strip() and not line.startswith("  ") or line.strip().startswith(("Results:", "Environmental Impact:")):
                    break
                if line.strip() and len(line) - len(line.lstrip()) < 2:
                    break
                code.append(line)
                j += 1
            c = textwrap.dedent("\n".join(code)).strip("\n")
            m = re.search(r"^(?:class|def) (\w+)|^(\w+) = \{", c, re.M)
            yield f"PDF block at line {i + 1} ({(m.group(1) or m.group(2)) if m else '?'})", c
            i = j
        else:
            i += 1

ENTRY = {  # entry point and the arguments the paper itself gives
    "MonteCarloAnalysis": "MonteCarloAnalysis().run_integrated_simulation()",
    "CCOAgent": None,  # needs initial_conditions and an environment the paper never defines
    "AcreEquityModel": "{y: AcreEquityModel().calculate_wealth_growth(y) for y in (10, 20)}",
    "InflationModel": "InflationModel().simulate_with_ptf()",
    "optimal_parameters": "optimal_parameters",
    "SystemStability": "SystemStability().calculate_risk_metrics()",
    "carbon_reduction_ptf": "carbon_reduction_ptf()",
    "ptf_job_creation": None,  # needs ptf_assets and automation_level by sector; the paper gives neither
    "calculate_ptf_enhanced_conversion": None,  # needs a member object with has_role(); not defined
}

def InflationRuns(ns):
    return ns["InflationModel"]().simulate_with_ptf()

def run(code, extra):
    ns, out = {}, io.StringIO()
    try:
        with contextlib.redirect_stdout(out):
            exec(extra, ns)
            exec(compile(code, "<printed>", "exec"), ns)
            m = re.search(r"^(?:class|def) (\w+)|^(\w+) = \{", code, re.M)
            name = m.group(1) or m.group(2)
            entry = ENTRY.get(name)
            if entry is None:
                return "defines only; no runnable entry point (needs inputs the paper does not give)"
            res = eval(entry, ns)
            if name == "InflationModel" and "np" in ns:
                runs = [InflationRuns(ns) for _ in range(1000)]
                res = {"one run (seed 0)": [round(x, 2) for x in res],
                       "mean over 1,000 runs": round(sum(sum(r) / len(r) for r in runs) / len(runs), 3),
                       "mean peak over 1,000 runs": round(sum(max(r) for r in runs) / len(runs), 3)}
            return "runs: " + repr(res)[:600]
    except Exception as e:
        return f"fails: {type(e).__name__}: {e}"

def main():
    root = pathlib.Path(sys.argv[1])
    rows = []
    for label, code in list(html_blocks(root)) + list(pdf_blocks(root)):
        extra = "import random\nimport numpy as np\n"
        if "random.normal" in code:
            extra = "import numpy as np\nrandom = np.random\nnp.random.seed(0)\n"
        else:
            extra += "random.seed(0)\nnp.random.seed(0)\n"
        rows.append((label, run(code, ""), run(code, extra), code))
    out = sys.argv[sys.argv.index("--out") + 1] if "--out" in sys.argv else None
    L = ["# Printed code from the modelling paper, run as printed (S30)", "",
         "Generated by `audits/early/run_printed_code.py`. Each block is run once as printed, then once with only the imports it plainly assumes (seed 0).", ""]
    for label, a, b, code in rows:
        L += [f"## {label}", "", f"- As printed: {a}", f"- With imports: {b}", "", "```python", code, "```", ""]
    text = "\n".join(L) + "\n"
    if out:
        pathlib.Path(out).write_text(text)
    for label, a, b, _ in rows:
        print(f"{label}\n  as printed: {a}\n  with imports: {b}")

if __name__ == "__main__":
    main()
