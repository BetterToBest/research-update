#!/usr/bin/env python3
"""Summarise the pre-v4.20 engine runs (step S30, item 3).

Usage: python3 audits/early/summarize_runs.py audits/early/runs/*.jsonl [--engines audits/early/engines.txt] [--out audits/early/engine-results.md]

Reads the JSON lines written by run_engines.js and reports, per engine, the Full Integration
headline figures as the page displayed them: poverty rate, Gini, median wealth and system
stability, with the no-program baseline the page showed beside each. For each figure: mean over
seeds and the 2.5th-97.5th percentile range of single runs (the spread a reader of one run could
have seen). The engines before v3.3 cannot be seeded; their seeds replace Math.random (see
run_engines.js).
"""
import json, re, statistics, sys, collections

def num(s):
    if s is None:
        return None
    m = re.search(r"(-?\$?-?[\d,]*\.?\d+)\s*([KkM]?)", s)
    if not m:
        return None
    v = float(m.group(1).replace("$", "").replace(",", ""))
    return v * {"K": 1e3, "k": 1e3, "M": 1e6}.get(m.group(2), 1)

def base(s, what):
    if not s:
        return None
    m = re.search(r"baseline \((-?[\d.]+)%\)", s) if what == "pov" else re.search(r"Baseline:? (-?\$?-?[\d.,]+[KM]?)", s)
    return num(m.group(1)) if m else None

KEYS = {  # figure: (tile ids, early ids)
    "poverty %": ("k-pov", "kpi-poverty", "kpi-pov"),
    "Gini": ("k-gini", "kpi-gini"),
    "median wealth $": ("k-wealth", "kpi-wealth"),
    "stability %": ("k-stab", "kpi-stability", "kpi-stab"),
}

def pick(k, ids):
    for i in ids:
        if i in k and re.search(r"\d", k[i]):
            return i
    return None

def q(xs, p):
    xs = sorted(xs)
    return xs[min(len(xs) - 1, max(0, int(round(p * (len(xs) - 1)))))]

def main():
    files = [a for a in sys.argv[1:] if a.endswith(".jsonl")]
    order, labels = [], {}
    if "--engines" in sys.argv:
        for l in open(sys.argv[sys.argv.index("--engines") + 1]):
            if l.strip() and not l.startswith("#"):
                c, lab = l.split(maxsplit=1)
                order.append(c); labels[c] = lab.strip()
    runs = collections.defaultdict(list)
    errs = collections.Counter()
    for f in files:
        for l in open(f):
            if l.strip():
                r = json.loads(l)
                runs[r["commit"]].append(r)
                labels.setdefault(r["commit"], r["label"])
                for e in r.get("errors", []):
                    errs[(r["commit"], e)] += 1
    order = [c for c in order if c in runs] + [c for c in runs if c not in order]
    L = ["# Engines before v4.20: Full Integration headline figures (S30)", "",
         "Generated by `audits/early/summarize_runs.py` from `runs/*.jsonl` (written by `run_engines.js`). "
         "Each engine is the page at that commit, run headless on its Full Integration preset ('optimal' before v3.5, 'reference' after) "
         "for each seed, and read as the page displayed it. Mean over seeds, then the 2.5th-97.5th percentile range of single runs. "
         "'Baseline' is the no-program comparison the page showed beside the figure.", "",
         "| Engine | Runs ok | Poverty % | Baseline poverty % | Gini | Baseline Gini | Median wealth | Baseline median wealth | Stability % |",
         "|---|---|---|---|---|---|---|---|---|"]
    summary = {}
    for c in order:
        ok = [r for r in runs[c] if r["status"] == "ok"]
        vals = collections.defaultdict(list)
        for r in ok:
            k = r["kpis"]
            for name, ids in KEYS.items():
                i = pick(k, ids)
                if i:
                    v = num(k[i])
                    if v is not None:
                        vals[name].append(v)
                    d = k.get(i + "-d")
                    b = base(d, "pov" if name == "poverty %" else "other")
                    if b is not None and name != "stability %":
                        vals["base " + name].append(b)
        def cell(name, fmt):
            xs = vals.get(name)
            if not xs:
                return "n/a"
            return f"{fmt(statistics.mean(xs))} ({fmt(q(xs, .025))}-{fmt(q(xs, .975))})"
        pct = lambda v: f"{v:.1f}"
        g = lambda v: f"{v:.3f}"
        usd = lambda v: f"${v / 1000:,.0f}K"
        L.append(f"| `{c}` {labels.get(c, '')} | {len(ok)}/{len(runs[c])} | {cell('poverty %', pct)} | {cell('base poverty %', pct)} | "
                 f"{cell('Gini', g)} | {cell('base Gini', g)} | {cell('median wealth $', usd)} | {cell('base median wealth $', usd)} | {cell('stability %', pct)} |")
        summary[c] = {k: statistics.mean(v) for k, v in vals.items() if v}
    if errs:
        L += ["", "Script errors the pages raised (count of runs):", ""]
        for (c, e), n in errs.most_common(30):
            L.append(f"- `{c}`: {e} ({n})")
    text = "\n".join(L) + "\n"
    if "--out" in sys.argv:
        open(sys.argv[sys.argv.index("--out") + 1], "w").write(text)
        json.dump(summary, open(sys.argv[sys.argv.index("--out") + 1].replace(".md", ".json"), "w"), indent=1)
    print(text)

if __name__ == "__main__":
    main()
