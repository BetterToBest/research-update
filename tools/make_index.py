#!/usr/bin/env python3
"""Write prereg/INDEX.md and audits/INDEX.md: one entry per Markdown file with its
title, length, first sentence and the line numbers of its sections, so a session can
grep the index and open only the section it needs. Run from the repository root:
    python3 tools/make_index.py
Rerun it whenever a file in prereg/ or audits/ is added or changed."""
import os, re, sys

def entry(path):
    lines = open(path, encoding='utf-8').read().split('\n')
    title = next((l[2:].strip() for l in lines if l.startswith('# ')), os.path.basename(path))
    first = ''
    def para_after(start):
        for l in lines[start:]:
            t = l.strip()
            if t.startswith('#') and start:
                return ''
            if t and not t.startswith(('#', '|', '-', '>', '<', '```')) and not t.startswith(('Committed', 'Oct ', 'Nov ')):
                return re.split(r'(?<=[.!?])\s', t, maxsplit=1)[0]
        return ''
    for i, l in enumerate(lines):
        if re.match(r'##\s+(Plain-words summary|In plain words|Why|What this)', l):
            first = para_after(i + 1)
            if first:
                break
    if not first:
        first = para_after(0)
    secs = []
    for i, l in enumerate(lines, 1):
        m = re.match(r'(#{2,3})\s+(.*)', l)
        if m:
            secs.append('%s %d' % (m.group(2).strip()[:48], i))
    return title, len(lines), first[:220], secs

def build(folder, blurb):
    out = ['# Index of %s/' % folder, '', blurb,
           'Generated by `python3 tools/make_index.py`; do not edit by hand. Grep it, then open the section with `sed -n A,Bp`.', '']
    for name in sorted(os.listdir(folder)):
        p = os.path.join(folder, name)
        if name == 'INDEX.md':
            continue
        if os.path.isdir(p):
            out.append('- `%s/` (folder, %d files)' % (name, len(os.listdir(p))))
        elif name.endswith('.md'):
            t, n, first, secs = entry(p)
            out += ['## %s (%d lines)' % (name, n), t, '']
            if first:
                out += [first, '']
            if secs:
                out += ['Sections (line): ' + ' · '.join(secs), '']
    open(os.path.join(folder, 'INDEX.md'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')

if os.path.basename(os.getcwd()) == 'tools':
    sys.exit('run from the repository root')
build('prereg', 'Preregistrations, amendments inside each file (see its "Amendments" section line).')
build('audits', 'Audits, triage notes and corrections packages.')
print('wrote prereg/INDEX.md and audits/INDEX.md')
